"""Build prices/aws-us-east-1.yaml from AWS's public price list files (dev-time script, not run by the plugin).

Inputs (download them first, see docs/prices.md):
  ec2.json         https://b0.p.awsstatic.com/pricing/2.0/meteredUnitMaps/ec2/USD/current/ec2-ondemand-without-sec-sel/US%20East%20(N.%20Virginia)/Linux/index.json  (gzip)
  AmazonRDS.json   https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonRDS/current/us-east-1/index.json
  AWSELB.json      https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AWSELB/current/us-east-1/index.json
  AmazonVPC.json   https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonVPC/current/us-east-1/index.json
  ec2_subset.csv   lines of https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonEC2/current/us-east-1/index.csv
                   for NatGateway-Hours and EBS:VolumeUsage*
Usage: python scripts/build_prices.py <input dir> <read date YYYY-MM-DD> > prices/aws-us-east-1.yaml
"""
import csv, gzip, json, sys
from pathlib import Path


def main(src: Path, read_date: str) -> None:
    ec2 = json.loads(gzip.decompress((src / "ec2.json").read_bytes()))
    items = ec2["regions"]["US East (N. Virginia)"]
    ec2_prices = {v["Instance Type"]: float(v["price"]) for v in items.values()
                  if v.get("Operating System", "Linux") == "Linux" and float(v["price"]) > 0}

    rds = json.loads((src / "AmazonRDS.json").read_text())
    rds_prices: dict = {}
    for sku, p in rds["products"].items():
        a = p["attributes"]
        if p.get("productFamily") != "Database Instance" or a.get("deploymentOption") != "Single-AZ":
            continue
        engine = {"PostgreSQL": "postgres", "MySQL": "mysql", "MariaDB": "mariadb"}.get(a.get("databaseEngine"))
        if not engine or a.get("licenseModel") not in (None, "No license required"):
            continue
        for t in rds["terms"]["OnDemand"].get(sku, {}).values():
            for pd in t["priceDimensions"].values():
                if pd["unit"] == "Hrs":
                    rds_prices.setdefault(engine, {})[a["instanceType"]] = float(pd["pricePerUnit"]["USD"])

    ebs, nat = {}, None
    rows = list(csv.reader((src / "ec2_subset.csv").read_text().splitlines()))
    header = next(r for r in rows if r and r[0] == "SKU")
    col = {name: i for i, name in enumerate(header)}
    ec2_csv_date = next(r[1] for r in rows if r and r[0] == "Publication Date")
    for r in rows:
        if len(r) < len(header) or r[col["TermType"]] != "OnDemand":
            continue
        usage, price = r[col["usageType"]], float(r[col["PricePerUnit"]])
        if usage == "NatGateway-Hours":
            nat = price
        elif usage.startswith("EBS:VolumeUsage"):
            vt = {"EBS:VolumeUsage": "standard", "EBS:VolumeUsage.gp2": "gp2", "EBS:VolumeUsage.gp3": "gp3",
                  "EBS:VolumeUsage.piops": "io1", "EBS:VolumeUsage.io2": "io2", "EBS:VolumeUsage.st1": "st1",
                  "EBS:VolumeUsage.sc1": "sc1"}.get(usage)
            if vt:
                ebs[vt] = price

    elb = json.loads((src / "AWSELB.json").read_text())
    elb_prices = {}
    for sku, p in elb["products"].items():
        op = p["attributes"].get("operation", "")
        kind = {"LoadBalancing:Application": "application", "LoadBalancing:Network": "network"}.get(op)
        if not kind or p.get("productFamily") not in ("Load Balancer-Application", "Load Balancer-Network"):
            continue
        for t in elb["terms"]["OnDemand"].get(sku, {}).values():
            for pd in t["priceDimensions"].values():
                if pd["unit"] == "Hrs" and "Outposts" not in pd["description"] and "Trust Store" not in pd["description"]:
                    elb_prices[kind] = float(pd["pricePerUnit"]["USD"])

    vpc = json.loads((src / "AmazonVPC.json").read_text())
    ipv4 = None
    for sku, p in vpc["products"].items():
        for t in vpc["terms"]["OnDemand"].get(sku, {}).values():
            for pd in t["priceDimensions"].values():
                if pd["description"].startswith("$0.005 per Idle public IPv4") or "In-use public IPv4 address per hour" in pd["description"]:
                    ipv4 = float(pd["pricePerUnit"]["USD"])

    out = []
    w = out.append
    w("# AWS us-east-1 on-demand prices, USD. Generated by scripts/build_prices.py; do not edit by hand.")
    w("# A type that is not listed here shows as 'price unknown'. Lights Out never guesses a price.")
    w(f"read: \"{read_date}\"")
    w("region: us-east-1")
    w("hours_per_month: 730   # AWS's own convention on its pricing pages")
    w("sources:")
    w("  ec2: \"https://b0.p.awsstatic.com/pricing/2.0/meteredUnitMaps/ec2/USD/current/ec2-ondemand-without-sec-sel/US%20East%20(N.%20Virginia)/Linux/index.json\"")
    w(f"  rds: \"https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonRDS/current/us-east-1/index.json (published {rds['publicationDate']})\"")
    w(f"  ebs_nat: \"https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonEC2/current/us-east-1/index.csv (published {ec2_csv_date})\"")
    w(f"  elbv2: \"https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AWSELB/current/us-east-1/index.json (published {elb['publicationDate']})\"")
    w(f"  ipv4: \"https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/AmazonVPC/current/us-east-1/index.json (published {vpc['publicationDate']})\"")
    w("  pages: \"https://aws.amazon.com/ec2/pricing/on-demand/ https://aws.amazon.com/rds/pricing/ https://aws.amazon.com/ebs/pricing/ https://aws.amazon.com/vpc/pricing/ https://aws.amazon.com/elasticloadbalancing/pricing/ https://aws.amazon.com/s3/pricing/\"")
    w("nat_gateway_hourly: %s   # plus $0.045 per GB processed (not counted)" % nat)
    w("public_ipv4_hourly: %s" % ipv4)
    w("elbv2_hourly:   # plus LCU usage (not counted)")
    for k in sorted(elb_prices):
        w(f"  {k}: {elb_prices[k]}")
    w("ebs_gb_month:")
    for k in sorted(ebs):
        w(f"  {k}: {ebs[k]}")
    w("rds_storage_gb_month: 0.115   # gp2/gp3 Single-AZ, same for postgres/mysql/mariadb in us-east-1")
    w("rds_hourly:   # Single-AZ, no licence")
    for eng in sorted(rds_prices):
        w(f"  {eng}:")
        for k in sorted(rds_prices[eng]):
            w(f"    {k}: {rds_prices[eng][k]}")
    w("ec2_hourly:   # Linux, shared tenancy")
    for k in sorted(ec2_prices):
        w(f"  {k}: {ec2_prices[k]}")
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]), sys.argv[2])
